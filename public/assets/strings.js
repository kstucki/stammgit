export function getT(lang) {
  const dict = STRINGS[lang] || STRINGS.de;
  const base = STRINGS.de;
  const fill = (tpl, vars = {}) => String(tpl).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  return {
    get(key, vars) {
      return fill(dict[key] ?? base[key] ?? key, vars);
    },
    getGenLabel(diff) {
      const map = dict.genMap || base.genMap;
      if (map[diff] !== undefined) return map[diff];
      const n = diff < 0 ? -diff - 2 : diff - 2;
      return fill(diff < 0 ? (dict.genUp ?? base.genUp) : (dict.genDown ?? base.genDown), { n });
    }
  };
}
