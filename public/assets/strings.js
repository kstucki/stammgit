export function getT(lang) {
  const code = (lang || 'de').split('-')[0];
  const dict = STRINGS[code] || STRINGS.de;
  const base = STRINGS.de;
  const fill = (tpl, vars = {}) => String(tpl).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  return {
    locale: code === 'pt' ? 'pt-BR' : code === 'en' ? 'en' : 'de-CH',
    get(key, vars) {
      // German long-lineage templates count great-prefixes; Portuguese names
      // the actual generation, without modifying the relationship path.
      if (code === 'pt' && /^rel(?:Ancestor|Descendant)5_/.test(key)) vars = { ...vars, n: Number(vars?.n) + 2 };
      if (code === 'en' && /^kinCousinDegree/.test(key)) {
        const n = Number(vars?.n), mod = n % 100;
        const suffix = mod >= 11 && mod <= 13 ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' }[n % 10] || 'th');
        vars = { ...vars, ordinal: `${n}${suffix}` };
      }
      return fill(dict[key] ?? base[key] ?? key, vars);
    },
    getGenLabel(diff) {
      const map = dict.genMap || base.genMap;
      if (map[diff] !== undefined) return map[diff];
      const n = diff < 0 ? -diff - 2 : diff - 2;
      return fill(diff < 0 ? (dict.genUp ?? base.genUp) : (dict.genDown ?? base.genDown), { n: code === 'pt' ? n + 2 : n });
    }
  };
}
